using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace EmailStudio.Generator;

/// <summary>
/// Emits deterministic C# code for generated email templates.
/// </summary>
public static class TemplateCodeEmitter
{
    public static string Emit(IEnumerable<TemplateFileInfo> templates)
    {
        var sortedTemplates = templates
            .Where(t => !t.IsLayout && !t.IsPartial)
            .OrderBy(t => t.TemplateName, StringComparer.Ordinal)
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace EmailStudio.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Generated typed email template renderers.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"EmailStudio.Generator\", \"0.1.0\")]");
        sb.AppendLine("public static partial class EmailTemplates");
        sb.AppendLine("{");

        foreach (var t in sortedTemplates)
        {
            string methodName = "Render" + SanitizeIdentifier(t.TemplateName);
            string constName = "RawTemplate_" + SanitizeIdentifier(t.TemplateName);
            string modelParamType = !string.IsNullOrWhiteSpace(t.ModelType)
                ? (t.ModelType!.StartsWith("global::") ? t.ModelType : "global::" + t.ModelType)
                : "object?";

            string modelParamDef = !string.IsNullOrWhiteSpace(t.ModelType)
                ? $"{modelParamType} model"
                : "object? model = null";

            string escapedContent = (t.Content ?? string.Empty).Replace("\"", "\"\"");

            sb.AppendLine($"    /// <summary>");
            sb.AppendLine($"    /// Renders the {t.TemplateName} email template.");
            sb.AppendLine($"    /// </summary>");
            sb.AppendLine($"    public static global::EmailStudio.EmailDraft {methodName}({modelParamDef}, string? culture = null)");
            sb.AppendLine("    {");
            sb.AppendLine($"        var options = new global::EmailStudio.EmailRenderOptions {{ Culture = culture }};");
            sb.AppendLine($"        return global::EmailStudio.EmailEngine.Render({constName}, model, options, \"{t.TemplateName}\");");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    private const string {constName} = @\"{escapedContent}\";");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string SanitizeIdentifier(string name)
    {
        var sb = new StringBuilder();
        foreach (char c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
            {
                sb.Append(c);
            }
        }
        string result = sb.ToString();
        return string.IsNullOrEmpty(result) ? "Template" : result;
    }
}
