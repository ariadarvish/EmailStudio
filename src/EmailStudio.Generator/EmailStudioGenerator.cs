using Microsoft.CodeAnalysis;

namespace EmailStudio.Generator;

/// <summary>
/// Incremental Roslyn source generator for EmailStudio templates.
/// Compiles .cshtml email templates into typed, zero-runtime-Razor C# render methods.
/// </summary>
[Generator]
public sealed class EmailStudioGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Pipeline registration for incremental execution (M2 implementation)
        var additionalTexts = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(".cshtml", System.StringComparison.OrdinalIgnoreCase));

        context.RegisterSourceOutput(additionalTexts.Collect(), static (spc, files) =>
        {
            // Generator marker output for initialization smoke tests
            spc.AddSource("EmailStudio.Generated.g.cs", "// <auto-generated/>\n// EmailStudio template generator active.\n");
        });
    }
}

